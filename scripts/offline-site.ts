// Vite plugin for the website build: makes the site installable and usable offline.
//
// It emits a web app manifest and a service worker that precaches every file of this build
// (including the lazily loaded chapters, the background worker and the fonts), so after one visit
// the app opens with no connection. The cache is named after a hash of the build's files: a new
// deploy installs a new cache, and the app offers to reload into it.
//
// The single-file writer edition doesn't use this: it is already offline, and file:// pages
// can't register service workers.
import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';

const MANIFEST = {
  name: 'Narrative Bridge',
  short_name: 'Narrative Bridge',
  description: 'Turn screenplays and prose into playable interactive stories: Ink, Twine, Unity and Unreal.',
  start_url: './',
  scope: './',
  display: 'standalone',
  background_color: '#283618',
  theme_color: '#283618',
  icons: [
    { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
  // Once installed (Chrome/Edge), the app can be chosen to open these files; App.tsx receives them
  // through the launch queue. Project files open directly; the rest go to the Import page.
  file_handlers: [
    { action: './', accept: { 'application/json': ['.json'] } },
    {
      action: './',
      accept: {
        'text/plain': ['.fountain', '.txt', '.md', '.ink', '.twee', '.tw'],
        'application/xml': ['.fdx'],
        'application/pdf': ['.pdf'],
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document': ['.docx'],
      },
    },
  ],
  launch_handler: { client_mode: 'focus-existing' },
};

/** Files from public/ that the app itself uses (og.png is only for link previews). */
const PUBLIC_FILES = ['icon-192.png', 'icon-512.png', 'apple-touch-icon.png'];

function serviceWorker(version: string, files: string[]): string {
  return `// Generated by scripts/offline-site.ts. Precaches this build so the app works offline.
const CACHE = 'narrative-bridge-${version}';
const FILES = ${JSON.stringify(['./', ...files])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('narrative-bridge-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

// The page asks for this when the writer chooses to reload into a new version.
self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // Pages: the network when online (so the offline edition and WRITERS.md stay current), else the cached app.
    event.respondWith(fetch(req).catch(() => caches.match(req).then((r) => r || caches.match('./'))));
    return;
  }
  // Build files have content hashes in their names, so a cached copy is always right.
  event.respondWith(caches.match(req).then((r) => r || fetch(req)));
});
`;
}

export function offlineSite(): Plugin {
  return {
    name: 'narrative-bridge-offline-site',
    apply: 'build',
    enforce: 'post', // after Vite has written index.html into the bundle
    transformIndexHtml() {
      return [
        { tag: 'link', attrs: { rel: 'manifest', href: 'manifest.webmanifest' }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'apple-touch-icon', href: 'apple-touch-icon.png' }, injectTo: 'head' },
      ];
    },
    generateBundle(_options, bundle) {
      const files = [...Object.keys(bundle).filter((f) => !f.endsWith('.map')), ...PUBLIC_FILES, 'manifest.webmanifest'].sort();
      const hash = createHash('sha256').update(files.join('\n'));
      for (const f of Object.keys(bundle).sort()) {
        const out = bundle[f];
        hash.update(out.type === 'chunk' ? out.code : out.source);
      }
      const version = hash.digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: JSON.stringify(MANIFEST, null, 2) });
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, files) });
    },
  };
}
