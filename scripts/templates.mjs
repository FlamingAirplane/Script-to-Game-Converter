// Turns the engine code under src/core/export/templates/ (real .cs, .h and .cpp files that editors and tools can
// check) into src/core/export/templates.generated.ts, which the exports import. The same module works in the web
// app, the tests and the command line, with no bundler tricks.
//
//   npm run templates           regenerate after editing a template
//   npm run templates -- --check   fail if the generated module is out of date (CI runs this through the tests)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dir = path.join(root, 'src/core/export/templates');
const out = path.join(root, 'src/core/export/templates.generated.ts');

/** CuePlayer.cs → CUE_PLAYER_CS */
export const constantFor = (file) => {
  const ext = path.extname(file).slice(1).toUpperCase();
  return `${path.basename(file, path.extname(file)).replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()}_${ext}`;
};

export function generate() {
  const entries = [];
  for (const engine of fs.readdirSync(dir).sort())
    for (const file of fs.readdirSync(path.join(dir, engine)).sort()) {
      // Git may check files out with Windows line endings; the exports always use \n.
      const text = fs.readFileSync(path.join(dir, engine, file), 'utf8').replace(/\r\n/g, '\n');
      entries.push({ name: constantFor(file), source: `${engine}/${file}`, text });
    }
  const names = new Set();
  for (const e of entries) {
    if (names.has(e.name)) throw new Error(`Two templates are both ${e.name}`);
    names.add(e.name);
  }
  return [
    '// Generated by scripts/templates.mjs from src/core/export/templates/. Do not edit: edit the template, then run',
    '// `npm run templates`.',
    '/* eslint-disable */',
    '',
    ...entries.map((e) => `/** templates/${e.source} */\nexport const ${e.name} = ${JSON.stringify(e.text)};\n`),
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = generate();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error('src/core/export/templates.generated.ts is out of date: run `npm run templates`.');
      process.exit(1);
    }
    console.log('Templates are up to date.');
  } else {
    fs.writeFileSync(out, text);
    console.log(`Wrote ${path.relative(root, out)}.`);
  }
}
