// Compiles src/core/readerCore.ts (the reader's own rules, with no imports) into plain JavaScript that the playable
// page embeds, so the page and the TypeScript code run the same functions.
//
//   npm run reader-core              regenerate after editing readerCore.ts
//   npm run reader-core -- --check   fail if the generated module is out of date (the tests run this too)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = path.join(root, 'src/core/readerCore.ts');
const out = path.join(root, 'src/core/readerCore.generated.ts');

export function generate() {
  const ts = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
  const js = transformSync(ts, { loader: 'ts', format: 'esm', target: 'es2020' }).code.replace(/^export /gm, '');
  return [
    '// Generated by scripts/reader-core.mjs from src/core/readerCore.ts. Do not edit: edit that file, then run',
    '// `npm run reader-core`.',
    '/* eslint-disable */',
    '',
    `export const READER_CORE_JS = ${JSON.stringify(js)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = generate();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error('src/core/readerCore.generated.ts is out of date: run `npm run reader-core`.');
      process.exit(1);
    }
    console.log('Reader core is up to date.');
  } else {
    fs.writeFileSync(out, text);
    console.log(`Wrote ${path.relative(root, out)}.`);
  }
}
