import { parseValue } from './markers';
import { parseAssignment, parseConditionExpr } from './expr';
import type { Condition, Effect } from '../isr';
import type { ParsedBlock, Parser } from './types';

// Ink import. Ink that uses only what the story model can represent becomes an ordinary editable
// story: knots and stitches are passages, VARs are variables (has_<item> ones are items), text,
// dialogue (NAME: line #speaker #paren), #scene and #transition tags, choices with {conditions},
// effects and diverts, fallback choices, diverts and endings. Narrative Bridge's own Ink comes back
// exactly as it was made.
//
// Anything beyond that (gathers, tunnels, threads, inline logic and alternatives, functions,
// visit counts, other tags…) is listed by inkUnsupported(). The importer then keeps the Ink exactly
// as written (passthrough, see buildStory) unless the writer chooses to convert it anyway, in which
// case those lines are kept as notes so nothing is lost silently.

export interface InkFeature {
  line: number;
  feature: string;
}

const KNOWN_TAGS = /^(speaker|paren|audio|scene):|^transition$/;
const GENERATOR_HEADER = /^(?:Generated by Narrative Bridge|Edit the source document or the Narrative Bridge project|Inventory: one Boolean per item)/;

/** Unescapes Narrative Bridge's escapeInk(): a backslash makes the next character literal. */
function unescape(s: string): string {
  return s.replace(/\\(.)/g, '$1');
}

/** Splits "text #tag #tag" on unescaped #, returning the text and the tags. */
function splitTags(line: string): { text: string; tags: string[] } {
  const parts: string[] = [];
  let cur = '';
  for (let i = 0; i < line.length; i++) {
    if (line[i] === '\\' && i + 1 < line.length) (cur += line[i] + line[i + 1]), i++;
    else if (line[i] === '#') (parts.push(cur), (cur = ''));
    else cur += line[i];
  }
  parts.push(cur);
  return { text: parts[0].trim(), tags: parts.slice(1).map((t) => t.trim()).filter(Boolean) };
}

/** True if the text has unescaped Ink syntax that the model can't represent ({…} logic, <> glue). */
function hasInlineLogic(s: string): string | null {
  const plain = s.replace(/\\./g, '');
  if (/[{}]/.test(plain)) return 'inline logic or alternatives ({…})';
  if (plain.includes('<>')) return 'glue (<>)';
  if (/<-/.test(plain)) return 'threads (<-)';
  return null;
}

function scan(text: string): { blocks: ParsedBlock[]; unsupported: InkFeature[] } {
  const blocks: ParsedBlock[] = [];
  const unsupported: InkFeature[] = [];
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  const generated = /Generated by Narrative Bridge/.test(text);
  // Knot and stitch names: a bare name used as a condition is a visit count.
  const knots = new Set<string>();
  for (const l of lines) {
    const m = /^\s*={1,}\s*(?:function\s+)?([A-Za-z_]\w*)/.exec(l);
    if (m) knots.add(m[1]);
  }
  const lossy = (line: number, feature: string, keep?: string) => {
    unsupported.push({ line, feature });
    if (keep !== undefined) blocks.push({ kind: 'unsupported', text: keep, reason: `Ink ${feature}`, line });
  };
  const cond = (src: string, line: number): Condition | null => {
    const c = parseConditionExpr(src);
    const ids = (x: Condition): string[] =>
      x.type === 'has_item' ? [x.itemId] : x.type === 'compare' ? [x.variableId] : x.type === 'not' ? ids(x.condition) : x.type === 'and' || x.type === 'or' ? x.conditions.flatMap(ids) : [];
    if (!c || ids(c).some((id) => knots.has(id))) {
      lossy(line, `condition {${src}}`);
      return null;
    }
    return c;
  };

  let knot = '';
  let inFunction = false;
  let sawKnot = false;
  let sawText = false;
  let lastPassage = -1; // index in blocks of the current passage marker
  let bodyStart = true; // nothing but the header so far in this passage
  let choice: Extract<ParsedBlock, { kind: 'marker' }> | null = null; // the choice whose body we are in
  let comment: { start: number; lines: string[] } | null = null;
  let unsupportedNote: { line: number; reason: string; lines: string[] } | null = null;

  const flushUnsupportedNote = () => {
    if (unsupportedNote) blocks.push({ kind: 'unsupported', text: unsupportedNote.lines.join('\n'), reason: unsupportedNote.reason, line: unsupportedNote.line });
    unsupportedNote = null;
  };

  for (let i = 0; i < lines.length; i++) {
    const ln = i + 1;
    const raw = lines[i];
    let t = raw.trim();

    // Block comments become notes.
    if (comment) {
      const end = t.indexOf('*/');
      comment.lines.push(end >= 0 ? t.slice(0, end) : t);
      if (end >= 0) {
        const note = comment.lines.join('\n').trim();
        if (note) blocks.push({ kind: 'note', text: note, line: comment.start, endLine: ln });
        comment = null;
      }
      continue;
    }
    if (t.startsWith('/*')) {
      const end = t.indexOf('*/');
      if (end >= 0) {
        const note = t.slice(2, end).trim();
        if (note) blocks.push({ kind: 'note', text: note, line: ln });
      } else comment = { start: ln, lines: [t.slice(2)] };
      continue;
    }
    // Line comments: Narrative Bridge's own markers, passage titles, or notes.
    if (t.startsWith('//')) {
      const c = t.slice(2).trim();
      if (unsupportedNote && /^\/\/\s{2,}/.test(t)) {
        unsupportedNote.lines.push(t.replace(/^\/\/\s{3}/, '').replace(/^\/\/\s*/, ''));
        continue;
      }
      flushUnsupportedNote();
      const unsup = /^\[unsupported: (.+)\]$/.exec(c);
      if (unsup) {
        unsupportedNote = { line: ln, reason: unsup[1], lines: [] };
        continue;
      }
      if (generated && (GENERATOR_HEADER.test(c) || (!sawKnot && !sawText && blocks.every((b) => b.kind === 'title' || b.kind === 'marker')))) continue;
      if (generated && bodyStart && lastPassage >= 0) {
        // "// Passage title (source line N)" right after a knot header.
        const b = blocks[lastPassage];
        if (b.kind === 'marker' && b.marker.type === 'passage') b.marker.title = c.replace(/\s*\(source line \d+\)$/, '');
        bodyStart = false;
        continue;
      }
      if (c) blocks.push({ kind: 'note', text: c, line: ln });
      continue;
    }
    flushUnsupportedNote();
    // Trailing comments on content lines are kept as notes (VAR lines use theirs as item names).
    const trailing = /^(VAR|CONST)\b/.test(t) ? null : /^(.*?[^:\\])\/\/(.*)$/.exec(t);
    if (trailing) {
      t = trailing[1].trim();
      if (trailing[2].trim()) blocks.push({ kind: 'note', text: trailing[2].trim(), line: ln });
    }
    if (!t) continue;

    if (/^(INCLUDE|EXTERNAL|LIST)\b/.test(t)) {
      lossy(ln, t.split(/\s/)[0]);
      continue;
    }
    if (/^TODO\b/.test(t)) {
      blocks.push({ kind: 'note', text: t, line: ln });
      continue;
    }

    // Knots and stitches.
    const knotM = /^={2,}\s*(function\s+)?([A-Za-z_]\w*)\s*(\([^)]*\))?\s*=*\s*$/.exec(t);
    if (knotM) {
      choice = null;
      inFunction = !!knotM[1];
      if (inFunction) {
        lossy(ln, 'functions');
        continue;
      }
      if (knotM[3]) lossy(ln, 'knot parameters');
      knot = knotM[2];
      sawKnot = true;
      lastPassage = blocks.length;
      bodyStart = true;
      blocks.push({ kind: 'marker', marker: { type: 'passage', id: knot, title: knot }, line: ln });
      continue;
    }
    if (inFunction) continue;
    const stitchM = /^=\s*([A-Za-z_]\w*)\s*(\([^)]*\))?\s*$/.exec(t);
    if (stitchM) {
      choice = null;
      if (stitchM[2]) lossy(ln, 'stitch parameters');
      lastPassage = blocks.length;
      bodyStart = true;
      blocks.push({ kind: 'marker', marker: { type: 'passage', id: `${knot}__${stitchM[1]}`, title: `${knot}.${stitchM[1]}` }, line: ln });
      continue;
    }

    // Variables: VAR has_<item> = false // Display name (consumable)
    const varM = /^(VAR|CONST)\s+([A-Za-z_]\w*)\s*=\s*(.+?)\s*(?:\/\/\s*(.*))?$/.exec(t);
    if (varM) {
      const [, , id, valueSrc, note] = varM;
      if (!/^(true|false|-?\d+|"[^"]*")$/.test(valueSrc)) lossy(ln, `variable set to an expression (${id})`);
      const value = parseValue(valueSrc);
      if (/^has_/.test(id) && typeof value === 'boolean') {
        const consumable = /\(consumable\)\s*$/.test(note ?? '');
        blocks.push({ kind: 'marker', marker: { type: 'item', id: id.slice(4), displayName: note ? note.replace(/\s*\(consumable\)\s*$/, '').trim() || undefined : undefined, consumable }, line: ln });
      } else blocks.push({ kind: 'marker', marker: { type: 'var', id, value }, line: ln });
      continue;
    }

    // Global tags before the story begins: # title: …, # author: …
    if (/^#/.test(t) && !sawKnot && !sawText) {
      for (const tag of splitTags(` ${t}`).tags) {
        const kv = /^(title|author):\s*(.*)$/i.exec(tag);
        if (kv) blocks.push({ kind: 'title', key: kv[1].toLowerCase(), value: unescape(kv[2]), line: ln });
        else lossy(ln, `tag #${tag.split(':')[0]}`);
      }
      continue;
    }

    // Logic lines.
    if (t.startsWith('~')) {
      const body = t.slice(1).trim();
      if (/^temp\b/.test(body)) lossy(ln, 'temporary variables', t);
      else if (/^return\b/.test(body)) lossy(ln, 'return');
      else {
        const effect = parseAssignment(body);
        if (!effect) lossy(ln, `logic (${body})`, t);
        else if (choice && choice.marker.type === 'choice') choice.marker.effects.push(effect);
        else blocks.push({ kind: 'marker', marker: { type: 'effect', effect }, line: ln });
      }
      bodyStart = false;
      continue;
    }

    // Choices: * / + [ {conditions} ] [text] [-> target]
    const choiceM = /^([*+])((?:\s*[*+])*)\s*(\([A-Za-z_]\w*\))?\s*((?:\{[^}]*\}\s*)*)(.*)$/.exec(t);
    if (choiceM) {
      bodyStart = false;
      sawText = true;
      if (choiceM[2]) lossy(ln, 'nested choices');
      if (choiceM[3]) lossy(ln, 'choice labels');
      const conditions: Condition[] = [];
      for (const m of choiceM[4].matchAll(/\{([^}]*)\}/g)) {
        const c = cond(m[1], ln);
        if (c) conditions.push(c);
      }
      const { text: rest, tags } = splitTags(choiceM[5]);
      if (tags.length) lossy(ln, 'choice tags');
      const divert = /(?:^|\s)->\s*([A-Za-z_][\w.]*)\s*$/.exec(rest);
      let body = divert ? rest.slice(0, divert.index).trim() : rest.trim();
      if (/->\s*->|->\s*$/.test(body)) lossy(ln, 'tunnels (->->)');
      const target = divert ? normaliseTarget(divert[1], knot) : '';
      if (!body) {
        // A choice with no text is Ink's invisible fallback: the passage's divert.
        if (conditions.length) lossy(ln, 'conditional fallback choices');
        if (target === 'END') blocks.push({ kind: 'marker', marker: { type: 'end' }, line: ln });
        else if (target) blocks.push({ kind: 'marker', marker: { type: 'divert', target }, line: ln });
        choice = null;
        continue;
      }
      const inline = hasInlineLogic(body.replace(/\[[^\]]*\]/, ''));
      if (inline) lossy(ln, inline);
      const bracket = /^(.*?)\[([^\]]*)\](.*)$/.exec(body.replace(/\\\[/g, '\u0001').replace(/\\\]/g, '\u0002'));
      let shown: string;
      if (bracket) {
        if (bracket[1].trim() || bracket[3].trim()) lossy(ln, 'choice text that is also printed after choosing');
        shown = `${bracket[1]}${bracket[2]}`;
      } else {
        lossy(ln, 'choice text that is also printed after choosing');
        shown = body;
      }
      body = unescape(shown.replace(/\u0001/g, '\\[').replace(/\u0002/g, '\\]')).trim();
      const effects: Effect[] = [];
      const block: ParsedBlock = { kind: 'marker', marker: { type: 'choice', once: choiceM[1] === '*', text: body || '(choice)', target, conditions, effects }, line: ln };
      blocks.push(block);
      choice = block;
      continue;
    }

    // Gathers.
    if (/^-(?!>)/.test(t)) {
      lossy(ln, 'gathers (-)', t);
      choice = null;
      continue;
    }

    // Diverts.
    const divertOnly = /^->\s*([A-Za-z_][\w.]*)\s*$/.exec(t);
    if (divertOnly) {
      bodyStart = false;
      const target = normaliseTarget(divertOnly[1], knot);
      if (choice && choice.marker.type === 'choice') {
        if (!choice.marker.target) choice.marker.target = target;
        else lossy(ln, 'choices with more than one divert');
        continue;
      }
      if (!sawKnot && !sawText && target !== 'END') blocks.push({ kind: 'marker', marker: { type: 'start', id: target }, line: ln });
      else blocks.push({ kind: 'marker', marker: target === 'END' ? { type: 'end' } : { type: 'divert', target }, line: ln });
      continue;
    }
    if (/->\s*->/.test(t) || /->\s*[A-Za-z_][\w.]*\s*->/.test(t)) {
      lossy(ln, 'tunnels (->->)', t);
      continue;
    }

    // Text.
    bodyStart = false;
    sawText = true;
    const { text: body, tags } = splitTags(t);
    const textDivert = /(?:^|[^\\])->\s*([A-Za-z_][\w.]*)\s*$/.exec(body);
    const content = textDivert ? body.slice(0, textDivert.index + (textDivert[0].startsWith('-') ? 0 : 1)).trim() : body;
    const inline = hasInlineLogic(content);
    if (inline) {
      lossy(ln, inline, t);
      continue;
    }
    if (choice) {
      lossy(ln, 'text shown after a choice', t);
      if (textDivert && choice.marker.type === 'choice' && !choice.marker.target) choice.marker.target = normaliseTarget(textDivert[1], knot);
      continue;
    }
    const tag = (name: string) => tags.find((x) => x.startsWith(`${name}:`))?.slice(name.length + 1).trim();
    for (const x of tags) if (!KNOWN_TAGS.test(x)) lossy(ln, `tag #${x.split(':')[0]}`);
    const scene = tag('scene');
    if (scene) blocks.push({ kind: 'marker', marker: { type: 'heading', text: scene }, line: ln });
    const plain = unescape(content);
    if (tags.includes('transition')) blocks.push({ kind: 'transition', text: plain, line: ln });
    else {
      const speech = /^([^:]{1,40}):\s+([\s\S]*)$/.exec(plain);
      const tagged = tag('speaker') !== undefined;
      if (speech && (tagged || /^[A-Z][A-Z0-9 .'’\-]*$/.test(speech[1].trim()))) blocks.push({ kind: 'dialogue', character: speech[1].trim(), parenthetical: tag('paren'), text: speech[2], line: ln });
      else if (plain) blocks.push({ kind: 'action', text: plain, line: ln });
    }
    if (textDivert) {
      const target = normaliseTarget(textDivert[1], knot);
      blocks.push({ kind: 'marker', marker: target === 'END' ? { type: 'end' } : { type: 'divert', target }, line: ln });
    }
  }
  flushUnsupportedNote();
  return { blocks, unsupported };
}

/** Ink features in `text` that the story model can't represent, by line. Empty means fully editable. */
export function inkUnsupported(text: string): InkFeature[] {
  return scan(text).unsupported;
}

export const inkParser: Parser = {
  format: 'ink',
  label: 'Ink',
  extensions: ['.ink'],
  sniff(text) {
    let s = 0;
    if (/^\s*={2,}\s*\w+\s*={0,}\s*$/m.test(text)) s += 0.5;
    if (/->\s*\w+/.test(text)) s += 0.3;
    if (/^\s*VAR\s+\w+\s*=/m.test(text)) s += 0.2;
    return Math.min(s, 1);
  },
  parse(text) {
    return { format: 'ink', blocks: scan(text).blocks, diagnostics: [] };
  },
};

// Ink "knot.stitch" paths map to "knot__stitch" passage ids; a bare stitch name inside a knot
// is resolved relative to that knot by the story builder.
function normaliseTarget(target: string, knot: string): string {
  if (!target) return '';
  if (target === 'END' || target === 'DONE') return 'END';
  if (target.includes('.')) return target.replace('.', '__');
  return knot ? `${target}|${knot}` : target;
}
