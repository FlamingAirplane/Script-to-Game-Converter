const q = (s: string) => `TEXT(${JSON.stringify(s)})`;

/** The playthrough routes, for the automation tests (the same data as StorySource/PlaythroughRoutes.json). */
export function routesH(routes: StoryRoute[]): string {
  const choiceLists = routes.map((r, i) => `    static const TCHAR* Route${i}Choices[] = { ${r.choices.length ? r.choices.map(q).join(', ') : 'nullptr'} };`);
  return `// Generated by Narrative Bridge. Regenerated on every export.
#pragma once

#include "CoreMinimal.h"

/**
 * Playthrough routes found when the story was exported: between them they reach every ending the automated playthroughs
 * reached. The NarrativeBridge.Playthrough automation tests replay them to check the story still plays as written.
 */
namespace NarrativeBridgeRoutes
{
    struct FRoute
    {
        const TCHAR* Name;
        /** The text of each choice to take (Continue breaks and exits to the game included). */
        const TCHAR* const* Choices;
        int32 NumChoices;
        /** The passage it ends in, or nullptr. */
        const TCHAR* Ending;
        /** The last line read, as ink prints it ("MIRA: Hello." for dialogue). */
        const TCHAR* LastLine;
    };

${choiceLists.join('\n')}

    static const FRoute All[] = { ${routes.length ? routes.map((r, i) => `{ ${q(r.name)}, Route${i}Choices, ${r.choices.length}, ${r.ending ? q(r.ending) : 'nullptr'}, ${q(r.lastLine)} }`).join(',\n        ') : '{ nullptr, nullptr, 0, nullptr, nullptr }'} };
    static const int32 NumRoutes = ${routes.length};
}
`;
}

