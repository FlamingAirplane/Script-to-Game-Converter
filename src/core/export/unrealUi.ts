// The Unreal export's story panel: a port of the Unity package's NarrativeView and NarrativeTheme. FNarrativeTheme has a
// field for every setting in UNITY_THEME_FIELDS (the Export page's Story UI card), read from Theme.json, or from a
// Narrative Theme data asset. UNarrativeStoryWidget is a UMG widget built in C++ from the theme and driven by the story
// component's events; UNarrativeStoryPanelComponent puts one on screen; ANarrativeDemoGameMode plays the story on its own.
// Filled with fillUnreal (unrealRuntime.ts).

import type { UnityTheme } from '../isr';
import { UNITY_THEME_FIELDS, type ThemeField } from './unityTheme';
import { DEMO_CPP, DEMO_H, PANEL_CPP, PANEL_H, THEME_CPP, WIDGET_CPP, WIDGET_H } from './templates.generated';
export { DEMO_CPP, DEMO_H, PANEL_CPP, PANEL_H, THEME_CPP, WIDGET_CPP, WIDGET_H };

/** The C++ name of a theme setting: PascalCase, with b in front for true/false ones (bShowSpeakers). */
export function themeFieldName(f: Pick<ThemeField, 'key' | 'kind'>): string {
  const pascal = f.key[0].toUpperCase() + f.key.slice(1);
  return f.kind === 'bool' ? `b${pascal}` : pascal;
}

/** sRGB hex to Unreal's linear colour (what FLinearColor::FromSRGBColor gives). */
export function linearColour(hex: string): { R: number; G: number; B: number; A: number } {
  const c = (i: number) => {
    const v = parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16) / 255;
    const l = v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
    return Math.round(l * 1e6) / 1e6;
  };
  return { R: c(0), G: c(1), B: c(2), A: 1 };
}

/** Theme.json for Unreal: every setting under its C++ name, colours as linear R, G, B, A. */
export function unrealThemeJson(t: UnityTheme): Record<string, unknown> {
  const out: Record<string, unknown> = { Preset: t.preset };
  for (const f of UNITY_THEME_FIELDS) {
    const v = t[f.key];
    out[themeFieldName(f)] = f.kind === 'colour' ? linearColour(v as string) : v;
  }
  return out;
}

const cppString = (s: string) => JSON.stringify(s);
const cppFloat = (n: number) => `${Number.isInteger(n) ? n.toFixed(1) : String(n)}f`;

function fieldDecl(f: ThemeField, t: UnityTheme): string {
  const v = t[f.key];
  const name = themeFieldName(f);
  const tip = [f.hint, f.kind === 'choice' ? `One of: ${f.choices.map(([c, l]) => `${c} (${l})`).join(', ')}.` : ''].filter(Boolean).join(' ');
  const meta = [`DisplayName = ${cppString(f.label)}`, ...(f.kind === 'number' ? [`ClampMin = "${f.min}"`, `ClampMax = "${f.max}"`] : []), ...(tip ? [`ToolTip = ${cppString(tip)}`] : [])];
  const head = `    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = ${cppString(f.group)}, meta = (${meta.join(', ')}))`;
  switch (f.kind) {
    case 'colour': {
      const c = linearColour(v as string);
      return `${head}\n    FLinearColor ${name} = FLinearColor(${cppFloat(c.R)}, ${cppFloat(c.G)}, ${cppFloat(c.B)}, 1.f);`;
    }
    case 'number':
      return f.integer ? `${head}\n    int32 ${name} = ${Math.round(v as number)};` : `${head}\n    float ${name} = ${cppFloat(Number(v))};`;
    case 'bool':
      return `${head}\n    bool ${name} = ${v ? 'true' : 'false'};`;
    default:
      return `${head}\n    FString ${name} = TEXT(${cppString(String(v))});`;
  }
}

/** NarrativeTheme.h: the theme's settings (defaults from the look chosen in Pen to Ink), a data asset, and loading. */
export function themeH(t: UnityTheme): string {
  return `// Generated by Pen to Ink. The story panel's look and behaviour.
#pragma once

#include "CoreMinimal.h"
#include "Engine/DataAsset.h"
#include "Kismet/BlueprintFunctionLibrary.h"
#include "NarrativeTheme.generated.h"

/**
 * Everything about the story panel's look and behaviour, in groups (colours, panel, text, speakers and scenes, typing and
 * pacing, choices and buttons, toolbar, scene pictures, character portraits, screen and sound). The story panel reads it
 * from Content/NarrativeBridge/Data/Theme.json (the look chosen in Pen to Ink), or from a Narrative Theme asset.
 */
USTRUCT(BlueprintType)
struct FNarrativeTheme
{
    GENERATED_BODY()

    /** The preset it started from (book, night, minimal or custom). */
    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "Colours")
    FString Preset = TEXT(${cppString(t.preset)});

${UNITY_THEME_FIELDS.map((f) => fieldDecl(f, t)).join('\n\n')}
};

/** A story panel look, to change in the editor (even while playing) and give to the story panel. Create Theme From Story makes one. */
UCLASS(BlueprintType)
class __API__ UNarrativeThemeAsset : public UDataAsset
{
    GENERATED_BODY()

public:
    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "Pen to Ink", meta = (ShowOnlyInnerProperties))
    FNarrativeTheme Theme;
};

UCLASS()
class __API__ UNarrativeThemeLibrary : public UBlueprintFunctionLibrary
{
    GENERATED_BODY()

public:
    /** The look chosen in Pen to Ink (Content/NarrativeBridge/Data/Theme.json); false (and the defaults) when it can't be read. */
    UFUNCTION(BlueprintCallable, Category = "Pen to Ink|Theme")
    static bool LoadStoryTheme(FNarrativeTheme& Theme);

    /** Where the panel sits, as fractions of the screen from the top left: X min, Y min, X max, Y max. */
    static FVector4 PanelRect(const FNarrativeTheme& Theme);
};
`;
}

