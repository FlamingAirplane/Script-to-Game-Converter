import type { UnityTheme } from '../isr';
import { UNITY_THEME_FIELDS, type ThemeField } from './unityTheme';

/** The C++ name of a theme setting: PascalCase, with b in front for true/false ones (bShowSpeakers). */
export function themeFieldName(f: Pick<ThemeField, 'key' | 'kind'>): string {
  const pascal = f.key[0].toUpperCase() + f.key.slice(1);
  return f.kind === 'bool' ? `b${pascal}` : pascal;
}

/** sRGB hex to Unreal's linear colour (what FLinearColor::FromSRGBColor gives). */
export function linearColour(hex: string): { R: number; G: number; B: number; A: number } {
  const c = (i: number) => {
    const v = parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16) / 255;
    const l = v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
    return Math.round(l * 1e6) / 1e6;
  };
  return { R: c(0), G: c(1), B: c(2), A: 1 };
}

/** Theme.json for Unreal: every setting under its C++ name, colours as linear R, G, B, A. */
export function unrealThemeJson(t: UnityTheme): Record<string, unknown> {
  const out: Record<string, unknown> = { Preset: t.preset };
  for (const f of UNITY_THEME_FIELDS) {
    const v = t[f.key];
    out[themeFieldName(f)] = f.kind === 'colour' ? linearColour(v as string) : v;
  }
  return out;
}

const cppString = (s: string) => JSON.stringify(s);
const cppFloat = (n: number) => `${Number.isInteger(n) ? n.toFixed(1) : String(n)}f`;

function fieldDecl(f: ThemeField, t: UnityTheme): string {
  const v = t[f.key];
  const name = themeFieldName(f);
  const tip = [f.hint, f.kind === 'choice' ? `One of: ${f.choices.map(([c, l]) => `${c} (${l})`).join(', ')}.` : ''].filter(Boolean).join(' ');
  const meta = [`DisplayName = ${cppString(f.label)}`, ...(f.kind === 'number' ? [`ClampMin = "${f.min}"`, `ClampMax = "${f.max}"`] : []), ...(tip ? [`ToolTip = ${cppString(tip)}`] : [])];
  const head = `    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = ${cppString(f.group)}, meta = (${meta.join(', ')}))`;
  switch (f.kind) {
    case 'colour': {
      const c = linearColour(v as string);
      return `${head}\n    FLinearColor ${name} = FLinearColor(${cppFloat(c.R)}, ${cppFloat(c.G)}, ${cppFloat(c.B)}, 1.f);`;
    }
    case 'number':
      return f.integer ? `${head}\n    int32 ${name} = ${Math.round(v as number)};` : `${head}\n    float ${name} = ${cppFloat(Number(v))};`;
    case 'bool':
      return `${head}\n    bool ${name} = ${v ? 'true' : 'false'};`;
    default:
      return `${head}\n    FString ${name} = TEXT(${cppString(String(v))});`;
  }
}

